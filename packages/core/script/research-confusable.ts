#!/usr/bin/env bun
// Writes src/research/confusable.ts: the letters that Unicode's confusables data (UTS #39, confusables.txt) reads as
// Latin ones, for the look-alike folding of the web fence and the research outbound check.
//
// It reads the data through ICU's spoof checker, which compiles confusables.txt in, so the table is pinned to the ICU
// and Unicode versions the file's header names. It downloads nothing. macOS ships ICU as libicucore; elsewhere, pass
// the path of an ICU built without version suffixes on its functions (uspoof_open, not uspoof_open_74).
//
//   bun script/research-confusable.ts [path to ICU, /usr/lib/libicucore.dylib by default]
//
// A letter is in the table when NFKD leaves it as it is (NFKD folds full-width and mathematical letters already), its
// skeleton without combining marks reads as one Latin letter, and it is not itself a letter of ASCII. A
// skeleton is the prototype of a whole class of look-alikes: "m" is "rn" and "I" is "l", so a skeleton that is the
// prototype of ASCII letters is written as those letters, the capital for a capital ("Ӏ" is "I") and the small letter
// for a small one ("ӏ" is "l"). Letters whose skeleton is a digit, a mark of punctuation or several letters are left
// out: Cyrillic "З" is a letter, not the digit 3, and "Ы" is not "bl".

import path from "node:path"
import { dlopen, FFIType, ptr, type Pointer } from "bun:ffi"

const OUTPUT = path.join(import.meta.dirname, "..", "src", "research", "confusable.ts")
const icu = dlopen(process.argv[2] ?? "/usr/lib/libicucore.dylib", {
  uspoof_open: { args: [FFIType.ptr], returns: FFIType.ptr },
  uspoof_getSkeleton: {
    args: [FFIType.ptr, FFIType.u32, FFIType.ptr, FFIType.i32, FFIType.ptr, FFIType.i32, FFIType.ptr],
    returns: FFIType.i32,
  },
  u_getVersion: { args: [FFIType.ptr], returns: FFIType.void },
  u_getUnicodeVersion: { args: [FFIType.ptr], returns: FFIType.void },
}).symbols

const status = new Int32Array(1)
const checker = icu.uspoof_open(ptr(status))
if (status[0]! > 0 || !checker) throw new Error(`ICU's spoof checker did not open (error ${status[0]})`)
const output = new Uint16Array(64)

const icuVersion = version(icu.u_getVersion)
const unicodeVersion = version(icu.u_getUnicodeVersion)
const ascii = [..."ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"]
// The ASCII letters each prototype stands for: "l" for "I" and "l", "rn" for "m".
const prototypes = Map.groupBy(ascii, skeleton)

const table = Array.from({ length: 0x110000 - 0x80 }, (_, index) => index + 0x80)
  .filter((code) => code < 0xd800 || code > 0xdfff)
  .map((code) => String.fromCodePoint(code))
  .filter((letter) => /^\p{L}$/u.test(letter) && letter.normalize("NFKD") === letter)
  .flatMap((letter) => {
    const shown = skeleton(letter)
      .normalize("NFD")
      .replace(/[\p{M}\p{Default_Ignorable_Code_Point}]/gu, "")
    if (shown === letter) return []
    const options = prototypes.get(shown)
    const capital = letter !== letter.toLowerCase()
    const latin = options
      ? (options.find((option) => (option !== option.toLowerCase()) === capital) ?? options[0]!)
      : /^[A-Za-z]$/.test(shown)
        ? shown
        : undefined
    return latin ? [[letter, latin] as const] : []
  })

const lines = table.map(([letter, latin]) => `  "${escaped(letter)}": "${latin}",`)
await Bun.write(
  OUTPUT,
  [
    'export * as ResearchConfusable from "./confusable"',
    "",
    `// Generated by script/research-confusable.ts from the confusables data (UTS #39) of ICU ${icuVersion} (Unicode ${unicodeVersion}).`,
    "// Do not edit it by hand: run the script again to update it.",
    "//",
    "// Letters of other scripts, and Latin letters of other shapes, that Unicode reads as Latin letters: Cherokee",
    '// "\\u13AA" and Lisu "\\uA4EE" are "A", Coptic "\\u2C98" is "M", Latin "\\u0269" is "i". Written by code point, so this',
    "// file shows every character it holds.",
    "export const LATIN: Readonly<Record<string, string>> = {",
    ...lines,
    "}",
    "",
  ].join("\n"),
)
console.log(`Wrote ${table.length} letters from ICU ${icuVersion} (Unicode ${unicodeVersion}) to ${OUTPUT}`)

function skeleton(text: string) {
  const units = Uint16Array.from({ length: text.length }, (_, index) => text.charCodeAt(index))
  status[0] = 0
  const length = icu.uspoof_getSkeleton(checker, 0, ptr(units), units.length, ptr(output), output.length, ptr(status))
  if (status[0]! > 0) throw new Error(`ICU could not read the skeleton of ${escaped(text)} (error ${status[0]})`)
  return String.fromCharCode(...output.subarray(0, length))
}

function version(read: (parts: Pointer) => void) {
  const parts = new Uint8Array(4)
  read(ptr(parts))
  return [...parts].join(".").replace(/(?:\.0)+$/, "")
}

function escaped(letter: string) {
  const code = letter.codePointAt(0)!
  const hex = code.toString(16).toUpperCase().padStart(4, "0")
  return code > 0xffff ? `\\u{${hex}}` : `\\u${hex}`
}
