describe("submission agent selection", () => {
  test("uses the plan agent only while Plan Mode is enabled", () => {
    const available = [
      { name: "plan", mode: "primary" },
      { name: "build", mode: "primary" },
    ]

    expect(resolveSubmissionAgent({ planMode: true, current: "build", available })).toBe("plan")
    expect(resolveSubmissionAgent({ planMode: false, current: "plan", available })).toBe("build")
  })

  test("preserves a non-plan agent when Plan Mode is disabled", () => {
    expect(
      resolveSubmissionAgent({
        planMode: false,
        current: "review",
        available: [{ name: "review", mode: "primary" }],
      }),
    ).toBe("review")
  })

  test("does not enable the completion judge in Plan Mode or trivial conversation", () => {
    expect(shouldUseCompletionJudge({ enabled: true, agent: "plan", difficulty: "complex" })).toBe(false)
    expect(shouldUseCompletionJudge({ enabled: true, agent: "build", difficulty: "trivial" })).toBe(false)
    expect(shouldUseCompletionJudge({ enabled: true, agent: "build", difficulty: "complex" })).toBe(true)
  })
})

