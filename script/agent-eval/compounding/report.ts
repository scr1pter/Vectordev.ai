// The dated report: a JSON file with every task's numbers for each arm, and a Markdown page that says what they show,
// week by week, with the caveats and the command that produced it. Pure: it renders what it is given.

import type { Arm, TaskRun } from "./harness"
import { totals, weekly, type Totals } from "./measure"
import { FACTS, TASKS } from "./tasks"

export type Meta = {
  readonly date: string
  readonly mode: "offline" | "live"
  readonly model: string
  readonly revision: string
  readonly machine: string
  readonly command: string
  readonly seconds: number
}

const NAMES: Record<Arm, string> = { off: "Brain off", on: "Brain on", blind: "Brain on, hidden from the model" }

export function json(meta: Meta, arms: Partial<Record<Arm, readonly TaskRun[]>>) {
  const entries = Object.entries(arms) as [Arm, readonly TaskRun[]][]
  return {
    ...meta,
    question:
      "On the same repository over time, does Vector with its brain need fewer tokens and steps, repeat fewer mistakes and pass more checks than Vector without it?",
    estimation:
      meta.mode === "offline"
        ? "Tokens are characters / 4 of each request as sent; cost at Claude Sonnet 4.5 list prices with a cold prompt cache per task."
        : "Tokens and cost as the provider reported them to Vector.",
    sequence: TASKS.map((task) => ({
      task: task.id,
      week: task.week,
      day: task.day,
      title: task.title,
      prompt: task.prompt,
      needs: task.needs,
      teaches: task.teaches.map((item) => item.fact),
      upload: task.upload ?? [],
    })),
    facts: FACTS.map((item) => ({ id: item.id, kind: item.kind, summary: item.summary, memory: item.memory?.text })),
    arms: Object.fromEntries(entries.map(([arm, runs]) => [arm, { name: NAMES[arm], totals: totals(runs), weeks: weekly(runs), tasks: runs }])),
  }
}

export function markdown(meta: Meta, arms: Partial<Record<Arm, readonly TaskRun[]>>) {
  const off = arms.off ?? []
  const on = arms.on ?? []
  const blind = arms.blind
  const sum = { off: totals(off), on: totals(on), ...(blind ? { blind: totals(blind) } : {}) } as Record<Arm, Totals>
  const present = (Object.keys(sum) as Arm[]).filter((arm) => arms[arm])
  // "7% fewer input tokens", "3% more tool steps".
  const change = (a: number, b: number, noun: string) =>
    a === 0 ? `the same ${noun}` : `${Math.abs(Math.round(((b - a) / a) * 100))}% ${b <= a ? "fewer" : "more"} ${noun}`
  const plural = (count: number, noun: string) => `${count} ${noun}${count === 1 ? "" : "s"}`
  const thousands = (value: number) => value.toLocaleString("en-US")
  const offline = (text: string) => (meta.mode === "offline" ? text : "not seen live")
  const usd = (value: number) => `$${value.toFixed(meta.mode === "offline" ? 2 : 4)}`
  const misses = on.flatMap((run) => run.mistakes.filter((item) => item.repeated).map((item) => ({ run, item })))
  const offLeaks = off.flatMap((run) => {
    const task = TASKS.find((item) => item.id === run.task)!
    return task.needs.filter((id) => {
      const taught = TASKS.findIndex((item) => item.teaches.some((teach) => teach.fact === id))
      return taught >= 0 && taught < TASKS.indexOf(task) && !run.mistakes.some((item) => item.fact === id)
    }).map((id) => ({ run, id }))
  })
  // Before the first task that needs something taught earlier the brain only costs; after it, it is paid back.
  function phases() {
    const turn = TASKS.find((task, index) => task.needs.some((id) => TASKS.slice(0, index).some((earlier) => earlier.teaches.some((teach) => teach.fact === id))))?.week
    if (!turn || turn <= 1) return []
    const span = (runs: readonly TaskRun[], late: boolean) => totals(runs.filter((run) => (run.week >= turn) === late))
    const [offEarly, onEarly, offLate, onLate] = [span(off, false), span(on, false), span(off, true), span(on, true)]
    if (!offEarly.tasks || !offLate.tasks || !onEarly.tasks || !onLate.tasks) return []
    return [
      "",
      `**When it pays.** In ${turn === 2 ? "week 1" : turn === 3 ? "weeks 1 and 2" : `weeks 1 to ${turn - 1}`}, while nothing learned was needed yet, the brain on sent ${change(offEarly.inputTokens, onEarly.inputTokens, "input tokens")} than the brain off: it was paying for its tool and saving what it learned. From week ${turn}, when the lessons came back, it sent ${change(offLate.inputTokens, onLate.inputTokens, "input tokens")} and took ${change(offLate.steps, onLate.steps, "tool steps")}, and passed every check on ${onLate.succeeded} of ${onLate.tasks} tasks where the brain off passed ${offLate.succeeded}.`,
    ]
  }
  const title = meta.mode === "offline" ? "Brain compounding benchmark" : `Brain compounding benchmark, live on ${meta.model}`
  const row = (cells: readonly (string | number)[]) => `| ${cells.join(" | ")} |`

  return [
    `# ${title}, ${longDate(meta.date)}`,
    "",
    `Generated by \`${meta.command}\` at revision \`${meta.revision}\` on ${meta.machine}, in ${Math.round(meta.seconds)} s. \`report.json\` beside this page holds every task's numbers for each arm.`,
    "",
    "## The question",
    "",
    `On the same repository over six weeks, does Vector with its brain need fewer tokens and steps, repeat fewer mistakes and pass more checks than Vector without it? Both arms get the same ${count(off.length || on.length)} with the same prompts, from the same starting files, on the same model. The only difference is whether what Vector learned in one task is there in the next.`,
    "",
    "## Result",
    "",
    row(["", ...present.map((arm) => NAMES[arm])]),
    row(["---", ...present.map(() => "---:")]),
    row(["Input tokens", ...present.map((arm) => thousands(sum[arm].inputTokens))]),
    row(["Of which memory's lines (recall, notes, pointers, results)", ...present.map((arm) => offline(thousands(sum[arm].memoryTokens)))]),
    row(["Of which the memory tool's definition", ...present.map((arm) => offline(thousands(sum[arm].memoryToolTokens)))]),
    row(["Provider requests", ...present.map((arm) => sum[arm].requests)]),
    row(["Tool steps", ...present.map((arm) => sum[arm].steps)]),
    row(["Of which memory calls", ...present.map((arm) => sum[arm].memoryCalls)]),
    row(["Files read again", ...present.map((arm) => sum[arm].rereads)]),
    row(["Mistakes", ...present.map((arm) => sum[arm].mistakes)]),
    row(["Mistakes repeated after the fact was taught", ...present.map((arm) => sum[arm].repeated)]),
    row(["Hidden checks passed", ...present.map((arm) => `${sum[arm].checksPassed} of ${sum[arm].checksTotal}`)]),
    row(["Tasks that passed every check", ...present.map((arm) => `${sum[arm].succeeded} of ${sum[arm].tasks} (${Math.round((sum[arm].succeeded / Math.max(1, sum[arm].tasks)) * 100)}%)`)]),
    row(["Input tokens per task that passed", ...present.map((arm) => (sum[arm].succeeded ? thousands(Math.round(sum[arm].inputTokens / sum[arm].succeeded)) : "–"))]),
    row([meta.mode === "offline" ? "Cost at Sonnet 4.5 list prices" : "Cost as reported", ...present.map((arm) => usd(sum[arm].costUsd))]),
    "",
    ...(on.length && off.length
      ? [
          `With the brain on, the agent repeated ${plural(sum.on.repeated, "mistake")} where the brain off repeated ${sum.off.repeated}, and passed every check on ${sum.on.succeeded} of ${sum.on.tasks} tasks against ${sum.off.succeeded}. Over the whole sequence it sent ${change(sum.off.inputTokens, sum.on.inputTokens, "input tokens")} (${thousands(sum.on.inputTokens)} against ${thousands(sum.off.inputTokens)}) and took ${change(sum.off.steps, sum.on.steps, "tool steps")}; per task that passed every check it sent ${thousands(Math.round(sum.on.inputTokens / Math.max(1, sum.on.succeeded)))} input tokens against ${thousands(Math.round(sum.off.inputTokens / Math.max(1, sum.off.succeeded)))}.`,
          "",
          meta.mode === "offline"
            ? `**What the brain costs, and why the tokens are close.** The brain-on arm paid ${thousands(sum.on.memoryTokens)} tokens for the lines memory added, ${thousands(sum.on.memoryToolTokens)} for the memory tool's definition on every request, and ${plural(sum.on.memoryCalls, "memory call")}; the brain off has no memory tool at all. What it saved was the steps of recovering from repeated mistakes: a failed check, a re-read, a fix, the check again. Most of every request is Vector's fixed system prompt and tool definitions, so a step not taken saves a whole request. A silent mistake costs nothing here, though: the brain-off arm finished its ${sum.off.tasks - sum.off.succeeded} failed tasks without knowing they were wrong, and the later session that finds and fixes each one is not part of this benchmark.`
            : "Most of every request is Vector's fixed system prompt and tool definitions, so the tokens follow the steps.",
          ...phases(),
        ]
      : []),
    ...(blind && blind.length
      ? [
          "",
          `**The control.** The third arm runs the brain exactly as the brain-on arm does, but the fake model server deletes everything the brain added to each request before the scripted model reads it. It repeated ${plural(sum.blind.repeated, "mistake")} and passed every check on ${sum.blind.succeeded} of ${sum.blind.tasks} tasks, ${sum.blind.repeated === sum.off.repeated && sum.blind.succeeded === sum.off.succeeded ? "the same as the brain off" : `against ${sum.off.repeated} and ${sum.off.succeeded} for the brain off`}, while still paying for the memory it could not see (${thousands(sum.blind.inputTokens)} input tokens). ${sum.blind.repeated >= sum.off.repeated && sum.blind.succeeded <= sum.off.succeeded ? "So the brain-on arm's advantage comes from what the brain put in the requests, not from the script knowing the answers." : "**It kept some of the advantage, so something other than what the brain put in the requests reached the scripted model: these results do not stand until that is found.**"}`,
        ]
      : []),
    "",
    "## Week by week",
    "",
    "Each week's own numbers, then the running total to the end of that week. Chart-ready: one row per week and arm.",
    "",
    row(["Week", "Arm", "Input tokens", "Tool steps", "Files read again", "Mistakes", "Repeated", "Checks passed", "Tasks passed", "Input tokens to date", "Repeated to date", "Tasks passed to date"]),
    row(["---:", "---", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:", "---:"]),
    ...weekly(off).flatMap((_, index) =>
      present.map((arm) => {
        const week = weekly(arms[arm] ?? [])[index]!
        return row([
          week.week,
          NAMES[arm],
          thousands(week.week_totals.inputTokens),
          week.week_totals.steps,
          week.week_totals.rereads,
          week.week_totals.mistakes,
          week.week_totals.repeated,
          `${week.week_totals.checksPassed}/${week.week_totals.checksTotal}`,
          `${week.week_totals.succeeded}/${week.week_totals.tasks}`,
          thousands(week.cumulative.inputTokens),
          week.cumulative.repeated,
          `${week.cumulative.succeeded}/${week.cumulative.tasks}`,
        ])
      }),
    ),
    "",
    "## Task by task",
    "",
    "What each task needed, what the brain brought into the model's first request, and how each arm did: input tokens, tool steps, then the facts it got wrong (an asterisk marks a fact an earlier task taught).",
    "",
    row(["Week", "Task", "Needs", "Brain brought", "Brain off", "Brain on", ...(blind ? ["Control"] : [])]),
    row(["---:", "---", "---", "---", "---", "---", ...(blind ? ["---"] : [])]),
    ...TASKS.flatMap((task) => {
      const at = (runs: readonly TaskRun[] | undefined) => runs?.find((run) => run.task === task.id)
      const cell = (run: TaskRun | undefined) =>
        run
          ? `${thousands(run.inputTokens)} · ${run.steps} steps${run.mistakes.length ? ` · wrong: ${run.mistakes.map((item) => `${item.fact}${item.repeated ? "*" : ""}`).join(", ")}` : ""}${run.success ? "" : " · **failed**"}`
          : "–"
      if (!at(off) && !at(on)) return []
      return [
        row([
          task.week,
          `${task.id}: ${task.title}`,
          task.needs.join(", ") || "–",
          at(on)?.delivered.join(", ") || "–",
          cell(at(off)),
          cell(at(on)),
          ...(blind ? [cell(at(blind))] : []),
        ]),
      ]
    }),
    "",
    "## Where the brain did not help",
    "",
    ...(misses.length
      ? misses.map(
          ({ run, item }) =>
            `- **${run.task}**, ${item.fact}: ${item.how}. ${run.recall.length ? `The brain's recall for it held ${plural(run.recall.length, "line")}, none stating the fact: ${run.recall.map((line) => `\`${line.replace(/^- /, "").slice(0, 90)}${line.length > 92 ? "…" : ""}\``).join("; ")}.` : "The brain recalled nothing for it."}`,
        )
      : ["- Nothing: every fact a task needed after it was taught was in the brain-on arm's requests."]),
    ...offLeaks.map(
      ({ run, id }) =>
        `- **${run.task}**, ${id}: the brain-off arm got this right without memory, because a file it read for the task already said it (an earlier task's change left it in the code).`,
    ),
    "",
    "## The sequence",
    "",
    "The repository is *ledger*, a small invoicing and refunds service in TypeScript (`script/agent-eval/compounding/fixture.ts`). The facts and tasks are in `tasks.ts`.",
    "",
    row(["Fact", "Kind", "Taught", "Needed again"]),
    row(["---", "---", "---", "---"]),
    ...FACTS.map((item) => {
      const taught = TASKS.find((task) => task.teaches.some((teach) => teach.fact === item.id))
      const later = TASKS.filter((task) => task.needs.includes(item.id) && taught && TASKS.indexOf(task) > TASKS.indexOf(taught))
      return row([
        item.summary,
        item.kind,
        taught ? `${taught.id} (week ${taught.week}, ${teaching(taught.id, item.id)})` : "–",
        later.map((task) => task.id).join(", ") || "–",
      ])
    }),
    "",
    "## How it is measured",
    "",
    "- **The arms.** *Brain off* is Vector with memory turned off: no memory tool (`permission: { memory: \"deny\" }`), its session and brain databases in memory and a fresh home folder for every task, so nothing carries from one task to the next and no `brain.db` is ever opened (the harness checks each task's home afterwards, and its tests plant a full `brain.db` there to show it is never read). *Brain on* keeps one home for the whole sequence; learning is on, and what the agent saves is in use from the next request, with Undo for the user (nobody undoes anything here). The brain's whole cost, its tool definition included, is charged to the brain-on arm.",
    "- **The same start.** Every task starts both arms from the same files: week 0 plus the reference solutions of the tasks before it, committed with the same dates. A mistake in week 2 does not change what week 3 starts from.",
    "- **The owner's own steps.** In week 2 the owner adds the refund policy PDF to Vector's memory (`vector memory doc add`); without the brain it only sits in the repository. Vector's reading of the repository's own docs is turned off (`vector memory repo-docs off`), so what the brain-on arm knows came from the sessions and that one document. Vector links documents to code in the background at most every ten minutes; weeks pass in seconds here, so before each task the harness runs the same pass (`vector memory links --relink`).",
    "- **The scripted model** (`policy.ts`) is a pure function of each request. It reads the files a task names, makes the change, runs the tests and the check, recovers from the errors it sees, follows the document pointers Vector adds to files it reads, saves what it learned when the memory tool is offered, and cites the memory it relied on. Where a task needs a fact, it gets it right only if the fact's words are somewhere in the request, from any source: the user, a memory line, a document card, an error, a file. Otherwise it makes the mistake a model without the fact makes. It never reads the disk or the brain.",
    "- **Mistakes** are read from what the run did, never from the script: an `npm install` in a pnpm repository, a check that failed on the stale generated route table, or a hidden acceptance test of a fact that failed. Hidden acceptance tests are written after the agent finishes and removed before the next task, so the agent never sees them.",
    "- **Tokens** are characters / 4 of each request as Vector sent it, the same estimate as the footprint benchmark. Cost is at Claude Sonnet 4.5 list prices under Anthropic's prompt-caching rules, with a cold cache at the start of every task, since days pass between them.",
    "",
    "## What this does not show",
    "",
    "- **It measures context and repetition, not answer quality.** The scripted model writes the code the task script gives it; whether a real model writes good code with the brain's help is a live question. The live mode (below) asks it.",
    "- **The scripted model explores less than a strong model would.** It never searches the repository for related code or documents on its own. A model that searched more would find some facts without the brain (the refund policy PDF is in `docs/specs/`), at the price of more reads and tokens.",
    "- **The fixture and the tasks were written alongside the brain, by the same team, knowing how recall matches.** Recall needs two words in common with a request, or a file the entry names. The memory lines the scripted model saves are written the way the memory tool asks (short, naming the commands, files and things they are about), and the teaching prompts were phrased the same way; none of them, nor any later prompt, was changed after the first run. Every prompt and memory line is in `report.json`, so the overlap between them can be checked, and the one fact recall did not bring is listed above.",
    "- **Time between tasks is not simulated.** All entries look recent to recall's recency weighting, and the linking pass is forced before each task as described above.",
    "- **Live results depend on the model.** A model may not save what it learns, may not read what the brain recalls, or may find the facts on its own.",
    "",
    "## Reproduce",
    "",
    "```",
    "bun script/agent-eval/compounding/run.ts --out <folder>",
    "```",
    "",
    "It needs Bun and git, no network and no API key, and takes about a minute and a half on the machine above. The same revision gives the same numbers, apart from wall-clock times and a token or two where the test runner prints how long it took (on a loaded machine a time can gain a digit), wherever the temporary folder's path has the same length (every request carries the repository's path, so a longer one adds a few tokens to each). Against a real model, after a cost estimate and under a hard spend cap:",
    "",
    "```",
    "bun script/agent-eval/compounding/run.ts --live --provider openai-compatible --base-url http://localhost:8000/v1 --model <id> --max-spend 5",
    "bun script/agent-eval/compounding/run.ts --live --provider anthropic --model claude-sonnet-4-5 --api-key-env ANTHROPIC_API_KEY --price-input 3 --price-output 15 --max-spend 20",
    "```",
    "",
  ].join("\n")
}

function count(tasks: number) {
  const words = ["no tasks", "one task", "two tasks", "three tasks", "four tasks", "five tasks", "six tasks", "seven tasks", "eight tasks", "nine tasks", "ten tasks", "eleven tasks", "twelve tasks", "thirteen tasks", "fourteen tasks", "fifteen tasks", "sixteen tasks"]
  return words[tasks] ?? `${tasks} tasks`
}

function teaching(task: string, id: string) {
  const item = TASKS.find((entry) => entry.id === task)!.teaches.find((teach) => teach.fact === id)
  if (item?.quote) return "the user says it"
  if (task === "t04-refund-request") return "the spec PDF says it"
  return "a check breaks"
}

function longDate(date: string) {
  return new Date(`${date}T12:00:00Z`).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" })
}
